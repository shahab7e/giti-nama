  // Fast resolver for any person or event -> [lon, lat, placeName]; with a year, where the person lived then.
  TL.personGeo = function (p, y) {
    const mv = y != null && TL.PEOPLE_MOVES[p.n];
    if (mv) { let cur = null; for (const st of mv) if (y >= st[0]) cur = st; if (cur) return [cur[1], cur[2], cur[3]]; }
    if (TL.PEOPLE_GEO[p.n]) return TL.PEOPLE_GEO[p.n];
    const anc = TL.MAP && TL.MAP.anchors && TL.MAP.anchors[p.r];
    return anc ? [anc[0], anc[1], (TL.regionById[p.r] && TL.regionById[p.r].n) || ''] : null;
  };
  // Birthplace followed by every stop reached by year y.
  TL.personPath = function (p, y) {
    const home = TL.personGeo(p); if (!home) return [];
    const pts = [[home[0], home[1]]];
    for (const st of TL.PEOPLE_MOVES[p.n] || []) if (y >= st[0]) pts.push([st[1], st[2]]);
    return pts;
  };
  const evCache = new WeakMap();
  TL.eventGeo = function (e) {
    if (evCache.has(e)) return evCache.get(e);
    const title = e.n || '', desc = e.d || '';
    let found = null;
    // Pass 1: exact match in event title
    for (let i = 0; i < TL.EVENT_GEO.length; i++) {
      const row = TL.EVENT_GEO[i];
      if (matchKey(title, row[0])) { found = [row[1], row[2], row[3]]; break; }
    }
    // Pass 2: city name in event title
    if (!found && TL.MAP && TL.MAP.cities) {
      for (const k of Object.keys(TL.MAP.cities)) {
        if (matchKey(title, k)) { const c = TL.MAP.cities[k]; found = [c[0], c[1], k]; break; }
      }
    }
    // Pass 3: exact match in description
    if (!found && desc) {
      for (let i = 0; i < TL.EVENT_GEO.length; i++) {
        const row = TL.EVENT_GEO[i];
        if (matchKey(desc, row[0])) { found = [row[1], row[2], row[3]]; break; }
      }
    }
    // Pass 4: city name in description
    if (!found && desc && TL.MAP && TL.MAP.cities) {
      for (const k of Object.keys(TL.MAP.cities)) {
        if (matchKey(desc, k)) { const c = TL.MAP.cities[k]; found = [c[0], c[1], k]; break; }
      }
    }
    if (!found) {
      const anc = TL.MAP && TL.MAP.anchors && TL.MAP.anchors[e.r];
      if (anc) found = [anc[0], anc[1], (TL.regionById[e.r] && TL.regionById[e.r].n) || ''];
    }
    evCache.set(e, found);
    return found;
  };
